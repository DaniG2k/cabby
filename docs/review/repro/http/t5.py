# JWT
def b64(x): return base64.urlsafe_b64encode(x).rstrip(b"=")
def jwt(payload, key=APP, alg="HS256"):
    h = b64(json.dumps({"alg": alg, "typ": "JWT"}).encode()); p = b64(json.dumps(payload).encode())
    sig = hmac.new(key, h + b"." + p, hashlib.sha256).digest()
    return (h + b"." + p + b"." + b64(sig)).decode()
tok = jwt({"ext": json.dumps({"user": "u1"}), "exp": int(time.time()) + 600})
exp = jwt({"ext": json.dumps({"user": "u1"}), "exp": int(time.time()) - 600})
none = jwt({"ext": "{}", "exp": int(time.time()) + 600}, alg="none").rsplit(".",1)[0] + "."
bad = jwt({"ext": "{}", "exp": int(time.time()) + 600}, key=b"zzz")
cmp("sse jwt ok (public stream disabled)", req("GET", "/events?stream=a&jid=" + tok, {"X-Request-ID": "r1"}), wait=0.8)
cmp("sse jwt header", req("GET", "/events?stream=a", {"X-Request-ID": "r1", "X-JID": tok}), wait=0.8)

# signed stream
def sign_stream(name):
    enc = base64.b64encode(json.dumps(name).encode()).decode()
    return enc + "--" + hmac.new(APP, enc.encode(), hashlib.sha256).hexdigest()
ss = urllib.parse.quote(sign_stream("a"))
